using System;
using System.Globalization;
using System.Text;

namespace JeepneyRush.Logic
{
    /// <summary>
    /// Generates the server catalog (jeepney prices, upgrade costs, mission pools,
    /// achievements, route unlocks) from the game's own definitions, so the Supabase
    /// database can never disagree with the client. Written to
    /// supabase/migrations/*_jr_catalog.sql by unity/tools/ExportCatalog; a test fails if the
    /// committed file is out of date.
    /// </summary>
    public static class CatalogExport
    {
        /// <summary>The first catalog migration. Later catalog changes go into NEW files
        /// (*_jr_catalog.sql with a newer timestamp): Supabase never re-runs a migration that was
        /// already applied, so editing a deployed file would silently do nothing.</summary>
        public const string FileName = "20261121000100_jr_catalog.sql";
        public const string FileSuffix = "_jr_catalog.sql";

        /// <summary>Newest catalog migration in a migrations folder (null if none).</summary>
        public static string LatestFile(string migrationsDir)
        {
            if (!System.IO.Directory.Exists(migrationsDir)) return null;
            var files = System.IO.Directory.GetFiles(migrationsDir, "*" + FileSuffix);
            if (files.Length == 0) return null;
            Array.Sort(files, StringComparer.Ordinal);
            return files[files.Length - 1];
        }

        /// <summary>Stat used by an achievement, read from a save (mirrors jr_private.stat_value).</summary>
        public static float StatValue(SaveData d, string key)
        {
            switch (key)
            {
                case "total_passengers": return d.totalPassengers;
                case "best_distance": return d.bestDistance;
                case "best_clean": return d.bestCleanDistance;
                case "total_coins": return d.totalCoins;
                case "total_deliveries": return d.totalDeliveries;
                case "total_power_ups": return d.totalPowerUps;
                case "total_wet_distance": return d.totalWetDistance;
                case "total_smooth_humps": return d.totalSmoothHumps;
                case "owned_jeepneys": return d.ownedJeepneys?.Count ?? 0;
                case "max_upgrade": { int m = 0; if (d.upgradeLevels != null) foreach (var l in d.upgradeLevels) m = Math.Max(m, l); return m; }
                case "routes_unlocked": { int n = 0; foreach (var e in Environments.All) if (Environments.IsUnlocked(e.Kind, d.bestDistance)) n++; return n; }
                default: return float.NaN;
            }
        }

        private static string Q(string s) => "'" + (s ?? "").Replace("'", "''") + "'";
        private static string F(float f) => f.ToString("0.###", CultureInfo.InvariantCulture);

        public static string Sql()
        {
            var sb = new StringBuilder();
            sb.Append("-- GENERATED by unity/tools/ExportCatalog from the C# game definitions. Do not edit by hand.\n");
            sb.Append("-- Re-generate: dotnet run --project unity/tools/ExportCatalog\n\n");
            sb.Append("delete from public.jr_catalog_jeepneys;\n");
            foreach (var j in JeepneyCatalog.All)
                sb.Append($"insert into public.jr_catalog_jeepneys (id, name, price, gem_price, stat_class) values ({Q(j.Id)}, {Q(j.DisplayName)}, {j.Price}, {j.GemPrice}, {(int)JeepneyClasses.For(j)});\n");
            sb.Append("\ndelete from public.jr_catalog_upgrades;\n");
            foreach (var k in Upgrades.All)
                for (int lv = 0; lv < Upgrades.MaxLevel; lv++)
                    sb.Append($"insert into public.jr_catalog_upgrades (kind, kind_name, from_level, cost) values ({(int)k}, {Q(k.ToString())}, {lv}, {Upgrades.Cost(k, lv)});\n");
            sb.Append("\ndelete from public.jr_catalog_missions;\n");
            void Pool(string period, (MissionType type, int min, int max, int step, string text)[] pool)
            {
                for (int i = 0; i < pool.Length; i++)
                {
                    var p = pool[i];
                    bool inRun = p.type <= MissionType.StreakInRun;
                    sb.Append($"insert into public.jr_catalog_missions (period, idx, type, min_target, max_target, step, text, in_run) values ({Q(period)}, {i}, {Q(p.type.ToString())}, {p.min}, {p.max}, {p.step}, {Q(p.text)}, {(inRun ? "true" : "false")});\n");
                }
            }
            Pool("daily", Missions.DailyPool);
            Pool("weekly", Missions.WeeklyPool);
            sb.Append("\ndelete from public.jr_catalog_achievements;\n");
            foreach (var a in Achievements.All)
                sb.Append($"insert into public.jr_catalog_achievements (id, name, target, reward, stat_key) values ({Q(a.Id)}, {Q(a.Name)}, {F(a.Target)}, {a.Reward}, {Q(a.StatKey)});\n");
            sb.Append("\ndelete from public.jr_catalog_routes;\n");
            foreach (var e in Environments.All)
                sb.Append($"insert into public.jr_catalog_routes (env, name, unlock_distance) values ({(int)e.Kind}, {Q(e.Name)}, {F(e.UnlockDistance)});\n");
            sb.Append("\ndelete from public.jr_catalog_products;\n");
            foreach (var p in Products.All)
                sb.Append($"insert into public.jr_catalog_products (id, kind, title, coins, gems, jeepneys, ad_free) values ({Q(p.Id)}, {Q(p.Kind == ProductKind.Consumable ? "consumable" : "non_consumable")}, {Q(p.Title)}, {p.Coins}, {p.Gems}, array[{string.Join(", ", Array.ConvertAll(p.Jeepneys, Q))}]::text[], {(p.AdFree ? "true" : "false")});\n");
            sb.Append("\n-- game constants used by the server rules\n");
            sb.Append("delete from public.jr_catalog_constants;\n");
            void C(string key, double v) => sb.Append($"insert into public.jr_catalog_constants (key, value) values ({Q(key)}, {v.ToString("0.######", CultureInfo.InvariantCulture)});\n");
            C("daily_count", Missions.DailyCount);
            C("weekly_count", Missions.WeeklyCount);
            C("daily_reward_base", 100);
            C("weekly_reward_base", 500);
            C("max_upgrade_level", Upgrades.MaxLevel);
            C("coin_bonus_per_level", 0.10);
            C("level_reward_per_level", 100);
            C("ad_daily_bonus_coins", AdPolicy.DailyBonusCoins);
            C("ad_max_double_coins", AdPolicy.MaxDoubleCoins);
            return sb.ToString();
        }
    }
}
